import fs from 'node:fs';
import path from 'node:path';
import init, { HwpDocument } from '@rhwp/core';
const wasm = fs.readFileSync(path.resolve('node_modules/@rhwp/core/rhwp_bg.wasm'));
await init({ module_or_path: wasm });
const doc = HwpDocument.createEmpty();
console.log('blank:', doc.createBlankDocument().slice(0, 200));
console.log('insertText:', doc.insertText(0, 0, 0, '생활기록부 출력 시험'));
console.log('split:', doc.splitParagraph(0, 0, 11));
const t = doc.createTable(0, 1, 0, 3, 3);
console.log('table:', t);
const r = JSON.parse(t);
const pp = r.paraIdx ?? 1, ci = r.controlIdx ?? 0;
const cells = ['번호','이름','본문','1','홍길동','규칙을 지키며 학급 활동에 참여함.\n둘째 줄','2','김영희','Byte 시험 ABC 123'];
cells.forEach((txt, i) => { try { console.log('cell', i, doc.insertTextInCell(0, pp, ci, i, 0, 0, txt).slice(0,80)); } catch (e) { console.log('cell err', i, String(e)); } });
const out = doc.exportHwpxWithReport();
console.log('loss:', out.contentLoss().slice(0, 300));
const bytes = out.takeBytes();
fs.mkdirSync('spike/out', { recursive: true });
fs.writeFileSync('spike/out/rhwp.hwpx', bytes);
console.log('written', bytes.length);
